"""
CARD-008: AI Message Generation Engine
Advanced AI-powered message generation with personalization scoring and A/B testing
"""

import asyncio
import logging
from datetime import datetime
from typing import List, Dict, Any, Optional, Tuple
from pydantic import BaseModel, Field
import json
import hashlib
import httpx
from enum import Enum
import os

logger = logging.getLogger(__name__)

class MessageTone(str, Enum):
    PROFESSIONAL = "professional"
    CASUAL = "casual"
    FRIENDLY = "friendly"
    DIRECT = "direct"

class MessageType(str, Enum):
    EMAIL = "email"
    LINKEDIN = "linkedin"
    SMS = "sms"
    FOLLOW_UP = "follow_up"

class MessageVariation(BaseModel):
    """Single message variation with scoring"""
    content: str
    subject: Optional[str] = None
    personalization_score: float = Field(ge=0, le=100)
    confidence_score: float = Field(ge=0, le=100)
    cta_strength: str
    tone_match: float = Field(ge=0, le=100)
    personalization_elements: List[str] = []
    word_count: int
    variation_type: str  # "primary", "alternative", "short"

class MessageGenerationRequest(BaseModel):
    """Request for message generation"""
    prospect_id: str
    prospect_name: str
    prospect_company: str
    prospect_title: str
    prospect_industry: str
    prospect_location: Optional[str] = None
    prospect_linkedin: Optional[str] = None
    campaign_goal: str
    message_type: MessageType
    tone: MessageTone
    additional_context: Optional[str] = None
    company_news: Optional[str] = None
    mutual_connections: Optional[List[str]] = None
    recent_activities: Optional[List[str]] = None

class MessageGenerationResponse(BaseModel):
    """Response with multiple message variations"""
    variations: List[MessageVariation]
    context_analysis: Dict[str, Any]
    generation_time_ms: int
    personalization_insights: List[str]
    ab_testing_setup: Dict[str, Any]
    nexus_ai_signature: str

class MessageGenerationEngine:
    """
    CARD-008: Advanced AI Message Generation Engine
    
    Features:
    - Multi-variation generation (3 variations per request)
    - Advanced prompt engineering with context building
    - Personalization scoring >80% target
    - Support for 4 tones and multiple message types
    - A/B testing framework integration
    - Nexus.ai branding and methodology
    """
    
    def __init__(self):
        self.openrouter_api_key = os.getenv('OPENROUTER_API_KEY')
        self.model = "anthropic/claude-sonnet-4-20250514"  # Latest Claude model
        self.client = httpx.AsyncClient(timeout=30.0)
        
        if not self.openrouter_api_key:
            logger.warning("OPENROUTER_API_KEY not found - message generation will be limited")
    
    async def generate_personalized_message(
        self, 
        request: MessageGenerationRequest
    ) -> MessageGenerationResponse:
        """
        Generate multiple personalized message variations
        
        CARD-008 Requirements:
        - 3 message variations per request
        - Personalization score >80%
        - <5 seconds generation time
        - Context-rich personalization
        """
        start_time = datetime.now()
        
        try:
            # Build rich context from prospect data
            context = await self._build_prospect_context(request)
            
            # Generate multiple variations concurrently
            variations = await self._generate_message_variations(request, context)
            
            # Score and rank variations
            scored_variations = await self._score_variations(variations, request, context)
            
            # Set up A/B testing configuration
            ab_testing = self._setup_ab_testing(scored_variations, request)
            
            # Calculate generation time
            generation_time = int((datetime.now() - start_time).total_seconds() * 1000)
            
            return MessageGenerationResponse(
                variations=scored_variations,
                context_analysis=context,
                generation_time_ms=generation_time,
                personalization_insights=self._extract_personalization_insights(context),
                ab_testing_setup=ab_testing,
                nexus_ai_signature="Generated by Nexus.ai - AI-Powered Lead Intelligence Platform"
            )
            
        except Exception as e:
            logger.error(f"❌ Message generation failed: {str(e)}")
            raise Exception(f"Message generation failed: {str(e)}")
    
    async def _build_prospect_context(self, request: MessageGenerationRequest) -> Dict[str, Any]:
        """Build rich context from prospect data"""
        context = {
            "prospect_profile": {
                "name": request.prospect_name,
                "company": request.prospect_company,
                "title": request.prospect_title,
                "industry": request.prospect_industry,
                "location": request.prospect_location
            },
            "company_insights": {
                "industry_trends": await self._get_industry_insights(request.prospect_industry),
                "company_size_estimation": self._estimate_company_size(request.prospect_company),
                "recent_news": request.company_news or "No recent news available"
            },
            "personalization_opportunities": {
                "title_relevance": self._analyze_title_relevance(request.prospect_title, request.campaign_goal),
                "industry_connections": self._find_industry_connections(request.prospect_industry),
                "location_insights": self._get_location_insights(request.prospect_location),
                "mutual_connections": request.mutual_connections or []
            },
            "campaign_context": {
                "goal": request.campaign_goal,
                "tone": request.tone,
                "message_type": request.message_type,
                "additional_context": request.additional_context
            }
        }
        
        return context
    
    async def _generate_message_variations(
        self, 
        request: MessageGenerationRequest, 
        context: Dict[str, Any]
    ) -> List[MessageVariation]:
        """Generate 3 message variations concurrently"""
        
        # Define variation strategies
        variation_strategies = [
            {
                "type": "primary",
                "approach": "comprehensive_personalization",
                "length": "standard"
            },
            {
                "type": "alternative", 
                "approach": "value_proposition_focused",
                "length": "detailed"
            },
            {
                "type": "short",
                "approach": "direct_and_concise",
                "length": "brief"
            }
        ]
        
        # Generate variations concurrently
        tasks = [
            self._generate_single_variation(request, context, strategy)
            for strategy in variation_strategies
        ]
        
        variations = await asyncio.gather(*tasks, return_exceptions=True)
        
        # Filter out exceptions and return valid variations
        valid_variations = [
            var for var in variations 
            if isinstance(var, MessageVariation)
        ]
        
        return valid_variations
    
    async def _generate_single_variation(
        self, 
        request: MessageGenerationRequest, 
        context: Dict[str, Any],
        strategy: Dict[str, str]
    ) -> MessageVariation:
        """Generate a single message variation using advanced prompt engineering"""
        
        # Build advanced prompt with Nexus.ai methodology
        prompt = await self._build_advanced_prompt(request, context, strategy)
        
        # Call OpenRouter API with Claude Sonnet 4
        response = await self._call_ai_api(prompt, request.tone, strategy)
        
        # Parse and structure response
        message_data = self._parse_ai_response(response, strategy)
        
        # Create message variation
        variation = MessageVariation(
            content=message_data["content"],
            subject=message_data.get("subject"),
            personalization_score=message_data["personalization_score"],
            confidence_score=message_data["confidence_score"],
            cta_strength=message_data["cta_strength"],
            tone_match=message_data["tone_match"],
            personalization_elements=message_data["personalization_elements"],
            word_count=len(message_data["content"].split()),
            variation_type=strategy["type"]
        )
        
        return variation
    
