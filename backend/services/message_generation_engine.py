    def _parse_ai_response(self, response: Dict[str, Any], strategy: Dict[str, str]) -> Dict[str, Any]:
        """Parse and validate AI response"""
        
        # Ensure all required fields exist
        parsed = {
            "content": response.get("content", "Message generation failed"),
            "subject": response.get("subject"),
            "personalization_score": min(100, max(0, response.get("personalization_score", 80))),
            "confidence_score": min(100, max(0, response.get("confidence_score", 85))),
            "cta_strength": response.get("cta_strength", "Medium"),
            "tone_match": min(100, max(0, response.get("tone_match", 85))),
            "personalization_elements": response.get("personalization_elements", [])
        }
        
        return parsed
    
    async def _score_variations(
        self, 
        variations: List[MessageVariation], 
        request: MessageGenerationRequest,
        context: Dict[str, Any]
    ) -> List[MessageVariation]:
        """Score and rank message variations"""
        
        for variation in variations:
            # Enhanced scoring based on Nexus.ai criteria
            variation.personalization_score = await self._calculate_personalization_score(
                variation, request, context
            )
        
        # Sort by personalization score (highest first)
        variations.sort(key=lambda x: x.personalization_score, reverse=True)
        
        return variations
    
    async def _calculate_personalization_score(
        self, 
        variation: MessageVariation,
        request: MessageGenerationRequest,
        context: Dict[str, Any]
    ) -> float:
        """Calculate comprehensive personalization score"""
        
        content = variation.content.lower()
        score = 0
        
        # Company name mentioned (20 points)
        if request.prospect_company.lower() in content:
            score += 20
        
        # Prospect name mentioned (15 points)
        if request.prospect_name.lower() in content:
            score += 15
        
        # Industry relevance (15 points)
        if request.prospect_industry.lower() in content:
            score += 15
        
        # Title/role mentioned (10 points)
        if request.prospect_title.lower() in content:
            score += 10
        
        # Campaign goal alignment (15 points)
        goal_keywords = request.campaign_goal.lower().split()
        if any(keyword in content for keyword in goal_keywords):
            score += 15
        
        # Context utilization (10 points)
        if any(element in content for element in variation.personalization_elements):
            score += 10
        
        # Call-to-action strength (10 points)
        cta_indicators = ["call", "meeting", "demo", "discuss", "schedule", "book"]
        if any(indicator in content for indicator in cta_indicators):
            score += 10
        
        # Length appropriateness (5 points)
        word_count = variation.word_count
        if 50 <= word_count <= 200:  # Optimal range
            score += 5
        
        return min(100, score)
    
    def _setup_ab_testing(
        self, 
        variations: List[MessageVariation],
        request: MessageGenerationRequest
    ) -> Dict[str, Any]:
        """Set up A/B testing configuration"""
        
        return {
            "test_id": hashlib.md5(f"{request.prospect_id}{datetime.now()}".encode()).hexdigest()[:8],
            "variations": [
                {
                    "id": f"var_{i+1}",
                    "type": var.variation_type,
                    "score": var.personalization_score,
                    "split_percentage": 33.33 if i < 3 else 0
                }
                for i, var in enumerate(variations[:3])
            ],
            "metrics_to_track": [
                "open_rate",
                "response_rate", 
                "click_rate",
                "conversion_rate"
            ],
            "test_duration_days": 14,
            "minimum_sample_size": 100
        }
    
